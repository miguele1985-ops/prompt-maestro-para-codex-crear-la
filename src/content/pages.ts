function mergeContentPages(basePages: ContentPage[], editablePages: ContentPage[]) {
  const merged = new Map(basePages.map((page) => [page.slug, page]));
  for (const page of editablePages) {
    if (!page.slug || !page.title || !page.description) continue;
    const existing = merged.get(page.slug);
    const fallback: ContentPage = existing || {
      slug: page.slug,
      title: page.title,
      description: page.description,
      body: [],
      seoTitle: page.title,
      seoDescription: page.description,
    };
    merged.set(page.slug, {
      ...fallback,
      ...page,
      body: page.body || fallback.body,
      seoTitle: page.seoTitle || fallback.seoTitle,
      seoDescription: page.seoDescription || fallback.seoDescription,
    });
  }
  return Array.from(merged.values());
}

